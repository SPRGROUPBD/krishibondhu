            messageBn = "ক্রেতা ${buyer.fullName} ${order.grandTotal.formatBdt()} (${paymentMethod.labelEn}, TxID: ${cleanTxId.ifBlank { "রসিদ" }}) পাঠিয়েছেন। টাকা বুঝে পেলে 'টাকা বুঝে পেয়েছি' নিশ্চিত করুন।",

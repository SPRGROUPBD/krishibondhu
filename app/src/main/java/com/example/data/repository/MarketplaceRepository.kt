    private fun addCalendarYears(baseMillis: Long, years: Int): Long {
        val cal = Calendar.getInstance().apply {
            timeInMillis = baseMillis
            add(Calendar.YEAR, years.coerceAtLeast(1))
        }
        return cal.timeInMillis
    }


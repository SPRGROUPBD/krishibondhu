            messageBn = "আপনার ${payment.amount.formatBdt()} (${payment.transactionId}) পেমেন্ট অনুমোদিত হয়েছে। এখন আপনি কৃষি বন্ধুর সব সুবিধা ব্যবহার করতে পারবেন।",

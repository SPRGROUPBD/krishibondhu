            targetEntity = "ActivationPayment",
            targetId = payment.id,
            detailsBn = "${user.fullName} — ${paymentMethod.labelEn} ${expectedFee.formatBdt()} | TxID: $cleanTxId"
        )
        db.notificationAuditDao().insertAuditLog(audit)
        rtdbSync.pushAuditLog(audit)
